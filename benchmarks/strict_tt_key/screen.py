"""STRICT_KEY_01 measurement-only screen: legacy versus strict TT search key.

Builds, from the current source with the production NNUE search flags, the
legacy-key control, the strict-key candidate
(``MAKHOS_STRICT_SEARCH_POSITION_KEY=1``) and the two TT-alias audit builds
generated by the 2139e329 review's ``instrument_tt.py``. On a seeded selection
from the *train* split of ``corpora/nnue_quiet_leaf_pilot_v4.jsonl`` it records,
per position and in a fresh search context each time:

* audit counters: TT hits, false hits, king-mask false hits, cutoffs, false
  cutoffs and king-mask false cutoffs;
* audit-versus-plain move/score/nodes/PV, which must agree per encoding;
* control-versus-strict move/score/nodes and median wall time over
  alternating repetitions.

The audit builds keep a full position beside every TT entry: never use them
for timing or play. Results go to a new directory; nothing is overwritten.
Validation and test rows of the corpus are never selected.
"""

from __future__ import annotations

import argparse
import ctypes
import hashlib
import json
import math
import os
import platform
import random
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from makhos.core import DEFAULT_RULES, parse_position  # noqa: E402
from makhos.native import NativeSearch  # noqa: E402

CORPUS = ROOT / "corpora" / "nnue_quiet_leaf_pilot_v4.jsonl"
MODEL = ROOT / "build" / "nnue_quantized_v1" / "model_a.mknnue"
INSTRUMENT = (
    ROOT / "benchmarks" / "game_reviews" / "2139e329d3c5def3" / "instrument_tt.py"
)
SOURCES = (
    "native/makhos_native.c",
    "native/makhos_native_nnue.c",
    "native/makhos_nnue_avx2_update.c",
)
WINDOWS_CLANG = Path(r"C:\Program Files\LLVM\bin\clang.exe")
PRODUCTION_FLAGS = [
    "-O3", "-march=x86-64", "-std=c17", "-Wall", "-Wextra", "-Werror",
    "-Wno-unused-function", "-shared",
]
AUDIT_FLAGS = ["-O3", "-march=x86-64", "-std=c17", "-shared"]
STRICT_DEFINE = "-DMAKHOS_STRICT_SEARCH_POSITION_KEY=1"
COUNTERS = (
    "hits", "false_hits", "king_false_hits",
    "cutoffs", "false_cutoffs", "king_false_cutoffs",
)
GROUPS = {
    # The no-loss risk band: kings on the board and seven to twelve pieces.
    "kings_7_to_12": lambda row: 7 <= row["piece_count"] <= 12 and row["king_count"] > 0,
    # A king-free middlegame control group.
    "no_kings_13_plus": lambda row: row["piece_count"] >= 13 and row["king_count"] == 0,
}


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def lower_priority() -> None:
    if os.name == "nt":
        kernel = ctypes.WinDLL("kernel32", use_last_error=True)
        kernel.GetCurrentProcess.restype = ctypes.c_void_p
        kernel.SetPriorityClass.argtypes = [ctypes.c_void_p, ctypes.c_uint32]
        if not kernel.SetPriorityClass(kernel.GetCurrentProcess(), 0x4000):
            raise ctypes.WinError(ctypes.get_last_error())
    else:
        os.nice(10)


def select_positions(count: int, seed: int) -> dict[str, list[dict]]:
    with CORPUS.open(encoding="utf-8") as stream:
        stream.readline()  # metadata header
        train = [
            row for row in map(json.loads, stream) if row["split"] == "train"
        ]
    train.sort(key=lambda row: row["sample_id"])
    rng = random.Random(seed)
    return {
        name: rng.sample([row for row in train if keep(row)], count)
        for name, keep in GROUPS.items()
    }


def compile_library(
    compiler: str, source: Path, output: Path, flags: list[str], defines: list[str]
) -> dict:
    platform_flags = (
        ["-Wl,/Brepro"] if os.name == "nt" else ["-fPIC", "-D_POSIX_C_SOURCE=200809L"]
    )
    command = [
        compiler, *flags, *platform_flags, *defines,
        "-I", str(ROOT / "native"), str(source), "-o", str(output),
    ]
    if os.name != "nt":
        command += ["-lm", "-lpthread"]
    process = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if process.returncode:
        raise RuntimeError(f"build failed for {output.name}:\n{process.stderr}")
    return {"path": str(output), "sha256": sha256(output), "command": command}


def build_libraries(compiler: str, lib_dir: Path) -> dict[str, dict]:
    lib_dir.mkdir()
    audit_source = lib_dir / "tt_alias_audit.c"
    subprocess.run(
        [sys.executable, "-B", str(INSTRUMENT), "--output", str(audit_source)],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    suffix = ".dll" if os.name == "nt" else ".so"
    nnue_source = ROOT / "native" / "makhos_native_nnue.c"
    return {
        "control": compile_library(
            compiler, nnue_source, lib_dir / f"control{suffix}", PRODUCTION_FLAGS, []
        ),
        "strict": compile_library(
            compiler, nnue_source, lib_dir / f"strict{suffix}",
            PRODUCTION_FLAGS, [STRICT_DEFINE],
        ),
        "audit_legacy": compile_library(
            compiler, audit_source, lib_dir / f"audit_legacy{suffix}", AUDIT_FLAGS, []
        ),
        "audit_strict": compile_library(
            compiler, audit_source, lib_dir / f"audit_strict{suffix}",
            AUDIT_FLAGS, [STRICT_DEFINE],
        ),
    }


def fresh_search(
    library: str, state, *, depth: int, hash_power: int, audit: bool
) -> tuple[dict, float, dict | None]:
    """Search once in a new context; return outcome, wall ms and audit counts."""
    with NativeSearch(
        library, hash_power=hash_power, persistent=True, nnue_model=MODEL
    ) as engine:
        started = time.perf_counter()
        result = engine.search(
            state,
            depth=depth,
            time_ms=None,
            no_progress_plies=DEFAULT_RULES.no_progress_plies,
            repetition_limit=DEFAULT_RULES.repetition_limit,
            history={state.position_key: 1},
        )
        wall_ms = (time.perf_counter() - started) * 1000.0
        counts = None
        if audit:
            values = (ctypes.c_uint64 * 20)()
            read = engine._library.makhos_loss_audit
            read.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_uint64)]
            read.restype = None
            read(engine._handle, values)
            counts = dict(zip(COUNTERS, map(int, list(values)[:6])))
    if result.depth != depth:
        raise RuntimeError(f"completed depth {result.depth}, expected {depth}")
    outcome = {
        "move": result.move.notation,
        "score": result.score,
        "nodes": result.nodes,
        "pv": [move.notation for move in result.pv],
    }
    return outcome, wall_ms, counts


def screen_position(
    index: int, row: dict, libraries: dict[str, dict], args: argparse.Namespace
) -> dict:
    state = parse_position(row["position"], reversible_plies=row["reversible_plies"])
    search = dict(depth=args.depth, hash_power=args.hash_power)
    outcomes: dict[str, list[dict]] = {"control": [], "strict": []}
    walls: dict[str, list[float]] = {"control": [], "strict": []}
    for repetition in range(args.repetitions):
        order = ("control", "strict") if (index + repetition) % 2 == 0 else (
            "strict", "control"
        )
        for name in order:
            outcome, wall_ms, _ = fresh_search(
                libraries[name]["path"], state, audit=False, **search
            )
            outcomes[name].append(outcome)
            walls[name].append(wall_ms)
    for name, runs in outcomes.items():
        if any(run != runs[0] for run in runs[1:]):
            raise RuntimeError(f"{name} is not deterministic on {row['sample_id']}")
    audit = {}
    for encoding, plain in (("legacy", "control"), ("strict", "strict")):
        outcome, _wall, counts = fresh_search(
            libraries[f"audit_{encoding}"]["path"], state, audit=True, **search
        )
        audit[encoding] = {
            "counts": counts,
            "matches_plain": outcome == outcomes[plain][0],
        }
    return {
        "sample_id": row["sample_id"],
        "position": row["position"],
        "reversible_plies": row["reversible_plies"],
        "piece_count": row["piece_count"],
        "king_count": row["king_count"],
        "control": outcomes["control"][0],
        "strict": outcomes["strict"][0],
        "control_median_ms": statistics.median(walls["control"]),
        "strict_median_ms": statistics.median(walls["strict"]),
        "audit": audit,
    }


def summarize(rows: list[dict]) -> dict:
    summary: dict = {"positions": len(rows)}
    for encoding in ("legacy", "strict"):
        counts = [row["audit"][encoding]["counts"] for row in rows]
        summary[f"{encoding}_audit_totals"] = {
            name: sum(item[name] for item in counts) for name in COUNTERS
        }
        summary[f"{encoding}_positions_with_false_cutoff"] = sum(
            item["false_cutoffs"] > 0 for item in counts
        )
        summary[f"{encoding}_positions_with_king_false_cutoff"] = sum(
            item["king_false_cutoffs"] > 0 for item in counts
        )
    summary["audit_plain_mismatches"] = sum(
        not row["audit"][encoding]["matches_plain"]
        for row in rows
        for encoding in ("legacy", "strict")
    )
    summary["same_move"] = sum(row["control"]["move"] == row["strict"]["move"] for row in rows)
    summary["same_score"] = sum(row["control"]["score"] == row["strict"]["score"] for row in rows)
    summary["strict_geometric_node_ratio"] = math.exp(statistics.fmean(
        math.log(row["strict"]["nodes"] / row["control"]["nodes"]) for row in rows
    ))
    summary["strict_total_node_ratio"] = (
        sum(row["strict"]["nodes"] for row in rows)
        / sum(row["control"]["nodes"] for row in rows)
    )
    summary["strict_time_ratio"] = (
        math.fsum(row["strict_median_ms"] for row in rows)
        / math.fsum(row["control_median_ms"] for row in rows)
    )
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--depth", type=int, default=20)
    parser.add_argument("--hash-power", type=int, default=20)
    parser.add_argument("--count", type=int, default=64, help="positions per group")
    parser.add_argument("--seed", type=int, default=20260925)
    parser.add_argument("--repetitions", type=int, default=3)
    parser.add_argument("--compiler", default=None)
    args = parser.parse_args()
    if args.output_dir.exists():
        raise SystemExit(f"output directory already exists: {args.output_dir}")
    compiler = args.compiler or (
        str(WINDOWS_CLANG) if WINDOWS_CLANG.is_file() else shutil.which("clang")
    )
    if compiler is None:
        raise SystemExit("clang is required")
    lower_priority()
    args.output_dir.mkdir(parents=True)
    libraries = build_libraries(compiler, args.output_dir / "lib")
    selection = select_positions(args.count, args.seed)
    started = time.time()
    groups = {}
    for name, rows in selection.items():
        results = []
        for index, row in enumerate(rows):
            results.append(screen_position(index, row, libraries, args))
            print(f"{name} {index + 1}/{len(rows)} {row['sample_id']}", flush=True)
        groups[name] = {"summary": summarize(results), "rows": results}
    report = {
        "format": "thai-makhos-strict-tt-key-screen-v1",
        "hypothesis": "STRICT_KEY_01",
        "config": {
            "depth": args.depth,
            "hash_power": args.hash_power,
            "count_per_group": args.count,
            "seed": args.seed,
            "repetitions": args.repetitions,
            "rules": {
                "repetition_limit": DEFAULT_RULES.repetition_limit,
                "no_progress_plies": DEFAULT_RULES.no_progress_plies,
            },
            "history": "fresh single-entry history per search",
            "corpus_split": "train",
        },
        "identity": {
            "sources": {path: sha256(ROOT / path) for path in SOURCES},
            "instrument_tt_sha256": sha256(INSTRUMENT),
            "corpus_sha256": sha256(CORPUS),
            "model_sha256": sha256(MODEL),
            "compiler": compiler,
            "compiler_version": subprocess.run(
                [compiler, "--version"], capture_output=True, text=True
            ).stdout.splitlines()[0],
            "platform": platform.platform(),
            "python": platform.python_version(),
            "libraries": libraries,
        },
        "elapsed_s": round(time.time() - started, 1),
        "groups": groups,
    }
    with (args.output_dir / "screen.json").open("x", encoding="utf-8") as stream:
        json.dump(report, stream, indent=1, sort_keys=True)
        stream.write("\n")
    for name, group in groups.items():
        print(name, json.dumps(group["summary"], sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
