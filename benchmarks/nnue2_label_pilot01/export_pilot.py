"""Quantize a pilot float model with the v1 exporter's own functions.

The v1 quantization contract is reused unchanged except for the source-model
binding, which names the pilot float model.  Writes the MKNNUE1 binary, a
parity report and the identity header a development search DLL is compiled
with (MAKHOS_NNUE_MODEL_IDENTITY_HEADER).
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from makhos.core import parse_position  # noqa: E402
from scratch import nnue_quantized_export as exporter  # noqa: E402


def c_bytes(hex_digest: str) -> str:
    values = [f"0x{hex_digest[i:i + 2].lower()}" for i in range(0, 64, 2)]
    lines = [", ".join(values[i:i + 8]) for i in range(0, 32, 8)]
    return "{\n    " + ",\n    ".join(lines) + "\n}"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--contract", type=Path, required=True, help="v1 quantization_contract_v2.json")
    parser.add_argument("--float-model", type=Path, required=True)
    parser.add_argument("--rows", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    contract = json.loads(args.contract.read_text(encoding="utf-8"))
    model_bytes = args.float_model.read_bytes()
    source_sha = hashlib.sha256(model_bytes).hexdigest().upper()
    contract["source_model_sha256"] = source_sha
    exporter.validate_contract(contract, source_model_sha256=source_sha)
    model = json.loads(model_bytes)
    quantized = exporter.quantize_model(model, contract)
    encoded = exporter.serialize_quantized_model(quantized, contract)
    if encoded != exporter.serialize_quantized_model(quantized, contract):
        raise SystemExit("serialization is not deterministic")
    loaded = exporter.parse_quantized_model(encoded, contract)
    with gzip.open(args.rows, "rt", encoding="utf-8") as stream:
        rows = []
        for row in map(json.loads, stream):
            if row["split"] != "validation":
                continue
            state = parse_position(row["position"], reversible_plies=row["reversible_plies"], ply=row["ply"])
            rows.append(exporter.ordered_feature_indices(state))
    parity = exporter._parity_report(model, loaded, rows)
    limits = contract["parity_limits"]
    bounds = exporter.prove_overflow_bounds(loaded, contract)
    verdict = all(parity[key] <= limits[key] for key in limits) and bounds["all_safe"]
    binary_sha = hashlib.sha256(encoded).hexdigest().upper()
    stem = args.float_model.name.removesuffix(".model.json")
    args.output_dir.mkdir(parents=True, exist_ok=True)
    report = {
        "format": "thai-makhos-nnue2-pilot-export-v1",
        "verdict": "PASS" if verdict else "FAIL",
        "source_model_sha256": source_sha,
        "binary_sha256": binary_sha,
        "binary_bytes": len(encoded),
        "base_contract_sha256": hashlib.sha256(args.contract.read_bytes()).hexdigest().upper(),
        "validation_parity": parity,
        "parity_limits": limits,
        "overflow_all_safe": bounds["all_safe"],
        "development_model": True,
    }
    (args.output_dir / f"{stem}.export.json").write_text(json.dumps(report, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    if not verdict:
        print(json.dumps(report["validation_parity"]))
        raise SystemExit("parity or overflow gate failed")
    (args.output_dir / f"{stem}.mknnue").write_bytes(encoded)
    header = (
        "/* Generated by benchmarks/nnue2_label_pilot01/export_pilot.py: a development model identity. */\n"
        f"#define MAKHOS_NNUE_BINARY_SHA256_TEXT \"{binary_sha}\"\n"
        f"#define MAKHOS_NNUE_SOURCE_SHA256_TEXT \"{source_sha}\"\n"
        f"static const uint8_t native_nnue_source_model_sha256[32] = {c_bytes(source_sha)};\n"
        f"static const uint8_t native_nnue_binary_sha256[32] = {c_bytes(binary_sha)};\n"
    )
    (args.output_dir / f"{stem}.identity.h").write_text(header, encoding="utf-8", newline="\n")
    print(json.dumps({"verdict": report["verdict"], "binary_sha256": binary_sha, "parity_mae": parity["mae"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
