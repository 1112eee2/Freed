"""Generate docs/architecture/NATIVE_COMPILE_FLAGS.md from native/makhos_native.c.

Every ``#ifndef MAKHOS_X`` / ``#define MAKHOS_X value`` pair is a compile-time
switch whose default is the production behaviour. The registry lists each one
with its default and source line, and marks the three that the build
orchestrator exposes as switches. ``--check`` exits 1 when the committed file
is out of date, so the registry cannot silently rot.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "native" / "makhos_native.c"
ORCHESTRATOR = ROOT / "tools" / "build" / "build_orchestrator.ps1"
OUTPUT = ROOT / "docs" / "architecture" / "NATIVE_COMPILE_FLAGS.md"

_IFNDEF = re.compile(r"^#ifndef\s+(MAKHOS_[A-Z0-9_]+)\s*$")
_DEFINE = re.compile(r"^#define\s+(MAKHOS_[A-Z0-9_]+)\s+(\S.*?)\s*$")
_SWITCH = re.compile(r"if \(\$(\w+)\) \{ \$Flags \+= '-D(MAKHOS_[A-Z0-9_]+)=")


def parse_defaults(source_text: str) -> list[tuple[str, str, int]]:
    """Return (name, default, line) for each guarded default, in file order."""
    lines = source_text.splitlines()
    found = []
    for index, line in enumerate(lines[:-1]):
        guard = _IFNDEF.match(line)
        define = _DEFINE.match(lines[index + 1])
        if guard and define and define.group(1) == guard.group(1):
            found.append((guard.group(1), define.group(2), index + 1))
    return found


def parse_switches(orchestrator_text: str) -> dict[str, str]:
    """Map a macro name to the orchestrator switch that sets it."""
    return {macro: switch for switch, macro in _SWITCH.findall(orchestrator_text)}


def render(source_text: str, orchestrator_text: str) -> str:
    switches = parse_switches(orchestrator_text)
    rows = [
        "# Native compile-time flags",
        "",
        "Generated by `tools/verification/native_flag_registry.py` from",
        "`native/makhos_native.c`; do not edit by hand. A flag is any",
        "`#ifndef MAKHOS_X` / `#define MAKHOS_X value` pair. The default is the",
        "behaviour of the accepted build. A flag with a non-default value belongs to",
        "a candidate and needs paired SPRT evidence before it can be promoted.",
        "",
        "Candidate flags added on unmerged branches (for example",
        "`MAKHOS_LMR_LOG` and `MAKHOS_NULL_EVAL_GUARD`) appear here only once their",
        "branch is merged.",
        "",
        "| Flag | Default | Line | Orchestrator switch |",
        "|---|---|---:|---|",
    ]
    for name, default, line in parse_defaults(source_text):
        switch = f"`-{switches[name]}`" if name in switches else ""
        rows.append(f"| `{name}` | `{default}` | {line} | {switch} |")
    return "\n".join(rows) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args(argv)
    text = render(
        SOURCE.read_text(encoding="utf-8"), ORCHESTRATOR.read_text(encoding="utf-8")
    )
    if options.check:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT} is out of date; rerun without --check", file=sys.stderr)
            return 1
        print("REGISTRY OK")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
